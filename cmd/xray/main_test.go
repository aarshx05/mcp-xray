package main

import (
	"os"
	"path/filepath"
	"testing"
)

func mustWriteTempFile(t *testing.T, dir, name string) string {
	t.Helper()
	path := filepath.Join(dir, name)
	if err := os.WriteFile(path, []byte("x"), 0644); err != nil {
		t.Fatalf("failed to create temp file %s: %v", path, err)
	}
	return path
}

// config-scan and pentest pass an empty outputPath when the user chose it
// with -o, so a user-chosen file is never auto-deleted; that must not be an
// error.
func TestCleanupGeneratedFiles_EmptyOutputPath(t *testing.T) {
	dir := t.TempDir()
	toolsFile := mustWriteTempFile(t, dir, "tools.json")
	testFile := mustWriteTempFile(t, dir, "test.yaml")

	if err := cleanupGeneratedFiles("", toolsFile, testFile, ""); err != nil {
		t.Fatalf("cleanupGeneratedFiles with empty outputPath returned error: %v", err)
	}
	for _, p := range []string{toolsFile, testFile} {
		if _, statErr := os.Stat(p); !os.IsNotExist(statErr) {
			t.Errorf("expected %s to be removed", p)
		}
	}
}

func TestCleanupGeneratedFiles_AllEmpty(t *testing.T) {
	if err := cleanupGeneratedFiles("", "", "", ""); err != nil {
		t.Fatalf("cleanupGeneratedFiles with all-empty paths returned error: %v", err)
	}
}

func TestCleanupGeneratedFiles_NonExistentOutputPathIsTolerated(t *testing.T) {
	missing := filepath.Join(t.TempDir(), "does-not-exist.sarif.json")
	if err := cleanupGeneratedFiles(missing, "", "", ""); err != nil {
		t.Fatalf("cleanupGeneratedFiles with a non-existent outputPath returned error: %v", err)
	}
}

func TestCleanupGeneratedFiles_RemovesEverythingWhenAutoGenerated(t *testing.T) {
	dir := t.TempDir()
	outputFile := mustWriteTempFile(t, dir, "findings.sarif.json")
	toolsFile := mustWriteTempFile(t, dir, "tools.json")
	testFile := mustWriteTempFile(t, dir, "test.yaml")
	testPlanDir := filepath.Join(dir, "pentest_plans")
	if err := os.Mkdir(testPlanDir, 0755); err != nil {
		t.Fatalf("failed to create test plan dir: %v", err)
	}

	if err := cleanupGeneratedFiles(outputFile, toolsFile, testFile, testPlanDir); err != nil {
		t.Fatalf("cleanupGeneratedFiles returned error: %v", err)
	}
	for _, p := range []string{outputFile, toolsFile, testFile, testPlanDir} {
		if _, statErr := os.Stat(p); !os.IsNotExist(statErr) {
			t.Errorf("expected %s to be removed", p)
		}
	}
}
